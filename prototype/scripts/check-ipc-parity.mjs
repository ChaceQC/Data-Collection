import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (relative) => fs.readFileSync(path.join(root, relative), "utf8");
const quoted = (source) => [...source.matchAll(/"([a-z][a-z0-9_]*)"/g)].map((match) => match[1]);
const sorted = (values) => [...new Set(values)].sort();
const diff = (left, right) => ({
  missing: left.filter((value) => !right.includes(value)),
  extra: right.filter((value) => !left.includes(value)),
});

const js = read("src/lib/ipcContracts.js");
const jsBlock = js.match(/export const IPC_COMMANDS = Object\.freeze\(\[([\s\S]*?)\]\);/u)?.[1] ?? "";
const jsCommands = sorted(quoted(jsBlock));

const manifest = read("src-tauri/build.rs");
const manifestBlock = manifest.match(/commands\s*\(&\[([\s\S]*?)\]\)/u)?.[1] ?? "";
const manifestCommands = sorted(quoted(manifestBlock));

const lib = read("src-tauri/src/lib.rs");
const handlerBlock = lib.match(/generate_handler!\[([\s\S]*?)\]/u)?.[1] ?? "";
const handlerCommands = sorted([...handlerBlock.matchAll(/commands::(?:[a-z0-9_]+::)*([a-z][a-z0-9_]*)\s*,?/g)].map((match) => match[1]));

const permissionNames = [];
for (const file of fs.readdirSync(path.join(root, "src-tauri/permissions/autogenerated"))) {
  if (file.endsWith(".toml")) permissionNames.push(file.slice(0, -5));
}
const generatedCommands = sorted(permissionNames);

const capabilityCommands = [];
for (const file of ["src-tauri/capabilities/default.json", "src-tauri/capabilities/floating.json"]) {
  const source = read(file);
  for (const match of source.matchAll(/"allow-([a-z0-9-]+)"/g)) {
    capabilityCommands.push(match[1].replaceAll("-", "_"));
  }
}
const capabilitySet = sorted(capabilityCommands);

const checks = [
  ["JS vs build manifest", jsCommands, manifestCommands],
  ["JS vs Rust handler", jsCommands, handlerCommands],
  ["JS vs generated ACL", jsCommands, generatedCommands],
  ["JS vs capabilities", jsCommands, capabilitySet],
];
const failures = [];
for (const [label, left, right] of checks) {
  const result = diff(left, right);
  if (result.missing.length || result.extra.length) {
    failures.push(`${label}: missing=[${result.missing.join(",")}] extra=[${result.extra.join(",")}]`);
  }
}
if (failures.length) {
  console.error(failures.join("\n"));
  process.exitCode = 1;
} else {
  console.log(`IPC parity passed: ${jsCommands.length} commands`);
}
